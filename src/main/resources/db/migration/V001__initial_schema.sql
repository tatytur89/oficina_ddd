-- Schema inicial PostgreSQL, alinhado às entidades JPA da aplicação.
-- O runner controla transação, lock e histórico; não adicionar COMMIT neste arquivo.

CREATE TABLE public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    documento VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255),
    telefone VARCHAR(255)
);

CREATE TABLE public.veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(255) NOT NULL,
    modelo VARCHAR(255) NOT NULL,
    ano INTEGER NOT NULL,
    placa VARCHAR(255) NOT NULL UNIQUE,
    cliente_id BIGINT NOT NULL
);

CREATE TABLE public.servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    descricao VARCHAR(255),
    preco NUMERIC(38, 2) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    tempo_estimado_minutos INTEGER
);

CREATE TABLE public.pecas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    codigo VARCHAR(255) NOT NULL UNIQUE,
    preco NUMERIC(38, 2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL,
    estoque_minimo INTEGER NOT NULL
);

CREATE TABLE public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255)
);

CREATE TABLE public.ordens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    veiculo_id BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    data_abertura TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    data_prevista_entrega TIMESTAMP(6) WITHOUT TIME ZONE,
    data_conclusao TIMESTAMP(6) WITHOUT TIME ZONE,
    observacoes VARCHAR(255),
    valor_servicos NUMERIC(38, 2) NOT NULL,
    valor_pecas NUMERIC(38, 2) NOT NULL,
    valor_total NUMERIC(38, 2) NOT NULL,
    chave_acesso VARCHAR(255),
    nota_avaliacao INTEGER,
    comentario_avaliacao VARCHAR(255),
    versao_orcamento BIGINT,
    decisao_orcamento BOOLEAN
);

-- Os IDs de catálogo são snapshots: exclusão de um item do catálogo não apaga histórico.
CREATE TABLE public.servicos_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servico_id BIGINT NOT NULL,
    nome_servico VARCHAR(255),
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(38, 2) NOT NULL,
    valor_total NUMERIC(38, 2) NOT NULL,
    ordem_servico_id BIGINT REFERENCES public.ordens_servico(id)
);

CREATE TABLE public.pecas_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peca_id BIGINT NOT NULL,
    nome_peca VARCHAR(255),
    codigo_peca VARCHAR(255),
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(38, 2) NOT NULL,
    valor_total NUMERIC(38, 2) NOT NULL,
    ordem_servico_id BIGINT REFERENCES public.ordens_servico(id)
);

CREATE INDEX idx_servicos_os_ordem_servico ON public.servicos_os(ordem_servico_id);
CREATE INDEX idx_pecas_os_ordem_servico ON public.pecas_os(ordem_servico_id);
